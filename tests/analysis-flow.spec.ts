import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'

async function seedOnce(page: Page, items: { productId: string; quantity: number }[]) {
  await page.addInitScript(items => {
    if (localStorage.getItem('fitmate.cart.v1') === null) localStorage.setItem('fitmate.cart.v1', JSON.stringify(items))
  }, items)
}
async function noOverflow(page: Page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth && scrollX === 0)).toBe(true)
  await expect(page.locator('main')).toHaveCSS('transform', 'none')
}
async function openReport(page: Page) {
  await page.getByRole('button', { name: '상세 정보 확인' }).click()
  await page.getByRole('button', { name: '전체 분석 리포트 보기' }).click()
}

for (const viewport of [{ width: 390, height: 844 }, { width: 375, height: 667 }, { width: 320, height: 568 }, { width: 1440, height: 900 }]) {
  test.describe(`교체 확인 흐름 ${viewport.width}x${viewport.height}`, () => {
    test.use({ viewport, isMobile: viewport.width < 600, hasTouch: viewport.width < 600 })
    test('선택 → 전후 비교 → 재계산 결과 → 보관 → 조합함 재진입과 새로고침', async ({ page }) => {
      const errors: string[] = []
      page.on('pageerror', error => errors.push(error.message))
      await seedOnce(page, [{ productId: 'P02', quantity: 3 }, { productId: 'M02', quantity: 1 }])
      await page.goto('/#optimize')
      await expect(page.getByTestId('before-score')).toHaveText('88점')
      await page.getByLabel('변경할 제품').selectOption('P01')
      await expect(page.getByTestId('after-score')).toHaveText('100점')
      await page.locator('.comparison-changes > summary').click()
      await expect(page.locator('.comparison-changes')).toContainText('R06')
      await noOverflow(page)
      await page.getByRole('button', { name: '변경 후 조합 확인하기' }).click()
      await expect(page).toHaveURL(/#result$/)
      await expect(page.getByRole('heading', { name: '조합 분석 결과' })).toBeVisible()
      await expect(page.locator('.score-value > span').first()).toHaveText('100')
      await expect.poll(() => page.evaluate(() => matchMedia('(min-width: 600px)').matches ? document.querySelector('.app-shell')!.scrollTop : scrollY)).toBe(0)
      await expect(page.locator('.change-confirmation')).toContainText('프로틴 B → 프로틴 A')
      await expect(page.locator('.result-product-summary')).toContainText('프로틴 A ×3')
      await expect(page.locator('.result-product-summary')).not.toContainText('프로틴 B')
      await page.getByRole('button', { name: /^주의할 점/ }).click()
      await expect(page.locator('.rule-detail')).toHaveCount(0)
      await expect(page.locator('#caution-details')).toContainText('안전하다는 의미가 아니며')
      await page.getByRole('button', { name: /^주의할 점/ }).click()
      await expect(page.getByRole('heading', { name: '조합 분석 결과' })).toHaveCSS('font-size', '28px')
      await expect(page.locator('.result-summary > p').first()).toHaveCSS('font-size', '15px')
      await noOverflow(page)
      await page.evaluate(() => document.fonts.ready)
      await page.screenshot({ path: `docs/qa/updated-result-${viewport.width}x${viewport.height}.png` })
      await page.getByRole('button', { name: '변경한 조합 저장하기' }).click()
      await expect(page.getByRole('button', { name: '내 정보에 저장됨' })).toBeVisible()
      const persisted = await page.evaluate(() => JSON.parse(localStorage.getItem('fitmate.cart.v1')!))
      expect(persisted).toEqual([{ productId: 'P01', quantity: 3 }, { productId: 'M02', quantity: 1 }])
      await page.getByRole('button', { name: '조합함으로 돌아가기' }).click()
      await expect(page).toHaveURL(/#cart$/)
      await expect(page.locator('.cart-row h2')).toHaveText(['프로틴 A', '레보티록신 경구제'])
      await expect(page.locator('.quantity-control > span').first()).toHaveText('3')
      await expect(page.locator('.cart-analysis-summary')).toContainText('100/100')
      await page.reload()
      await expect(page.locator('.cart-row h2')).toHaveText(['프로틴 A', '레보티록신 경구제'])
      await expect(page.locator('.quantity-control > span').first()).toHaveText('3')
      await openReport(page)
      await expect(page.locator('.score-value > span').first()).toHaveText('100')
      await expect(page.getByRole('button', { name: '내 정보에 저장됨' })).toBeVisible()
      await noOverflow(page)
      expect(errors).toEqual([])
    })
  })
}

test('점수가 낮아지는 교체도 새 주의사항과 실제 결과를 일치시킨다', async ({ page }) => {
  await seedOnce(page, [{ productId: 'P01', quantity: 1 }, { productId: 'M01', quantity: 1 }])
  await page.goto('/#optimize')
  await expect(page.getByTestId('before-score')).toHaveText('100점')
  await page.getByLabel('변경할 제품').selectOption('P03')
  await expect(page.getByTestId('after-score')).toHaveText('75점')
  await expect(page.locator('.demo-score-delta')).toHaveText('-25점')
  await page.locator('.comparison-changes > summary').click()
  await expect(page.locator('.comparison-changes .rule-detail')).toContainText('R28')
  await expect(page.locator('.comparison-changes .rule-detail')).toContainText('high')
  await page.getByRole('button', { name: '변경 후 조합 확인하기' }).click()
  await expect(page.locator('.score-value > span').first()).toHaveText('75')
  await page.getByRole('button', { name: /^주의할 점/ }).click()
  await expect(page.locator('#caution-details')).toContainText('복용약 병용 확인')
  await expect(page.locator('.rule-detail')).toContainText('R28')
})

test('추가·삭제·수량 변경에 따라 조합함과 결과의 실제 분석 상태가 갱신된다', async ({ page }) => {
  await seedOnce(page, [{ productId: 'P01', quantity: 1 }, { productId: 'M02', quantity: 1 }])
  await page.goto('/#cart')
  await expect(page.locator('.cart-analysis-summary')).toContainText('100/100')
  await page.getByRole('button', { name: '프로틴 A 수량 늘리기' }).click()
  await expect(page.locator('.cart-analysis-summary')).toContainText('3용기')
  await expect(page.locator('.cart-analysis-summary')).toContainText('100/100')
  await page.getByRole('navigation').getByRole('button', { name: '탐색', exact: true }).click()
  await page.getByRole('searchbox').fill('프로틴 B')
  await page.getByRole('button', { name: /^프로틴 B 조합함에 추가/ }).click()
  await page.getByRole('navigation').getByRole('button', { name: /조합함/ }).click()
  await expect(page.locator('.cart-analysis-summary')).toContainText('88/100')
  await page.getByRole('navigation').getByRole('button', { name: '탐색', exact: true }).click()
  await page.getByRole('searchbox').fill('철분')
  await page.getByRole('button', { name: /^철분제 조합함에 추가/ }).click()
  await page.getByRole('navigation').getByRole('button', { name: /조합함/ }).click()
  await expect(page.locator('.cart-analysis-summary')).toContainText('76/100')
  await page.getByRole('button', { name: '선택삭제' }).click()
  await page.getByRole('checkbox', { name: '프로틴 B 삭제 선택' }).check()
  await page.getByRole('button', { name: '선택한 1개 삭제' }).click()
  await expect(page.locator('.cart-analysis-summary')).toContainText('88/100')
  await openReport(page)
  await expect(page.locator('.score-value > span').first()).toHaveText('88')
  await page.getByRole('button', { name: /^주의할 점/ }).click()
  await expect(page.locator('.rule-detail')).toHaveCount(1)
  await expect(page.locator('.rule-detail')).toContainText('R07')
  await page.locator('.analysis-limitations > summary').click()
  await page.locator('.deferred-rule-details > summary').click()
  await expect(page.locator('.deferred-rule')).toHaveCount(12)
  await expect(page.locator('.deferred-rule').filter({ hasText: 'INT-005' })).toContainText('potassium_supplement')
})
