import { test, expect } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => {
    localStorage.setItem('fitmate.intro.seen.v1', 'true')
    if (!localStorage.getItem('fitmate.cart.v1')) localStorage.setItem('fitmate.cart.v1', JSON.stringify([{ productId: 'P02', quantity: 3 }, { productId: 'M02', quantity: 1 }]))
  })
})

test('조합함의 상세 바로 아래 최적화 → 실제 재계산 → 결과 → 저장·복원', async ({ page }) => {
  await page.goto('/#cart')
  const detail = page.getByRole('button', { name: '상세 정보 확인', exact: true })
  const optimize = page.getByRole('button', { name: '최적화 분석', exact: true })
  await expect(optimize).toBeVisible()
  const detailBox = await detail.boundingBox(), optimizeBox = await optimize.boundingBox()
  expect(optimizeBox!.y).toBeGreaterThanOrEqual(detailBox!.y + detailBox!.height)
  const oldCart = await page.evaluate(() => localStorage.getItem('fitmate.cart.v1'))
  await optimize.click()
  await expect(page).toHaveURL(/#optimize$/)
  await expect(page.getByTestId('before-score')).toHaveText('88점')
  await expect(page.getByTestId('after-score')).toHaveText('100점')
  expect(await page.evaluate(() => localStorage.getItem('fitmate.cart.v1'))).toBe(oldCart)
  await page.getByRole('button', { name: '변경 후 조합 확인하기' }).click()
  await expect(page).toHaveURL(/#result$/)
  await expect(page.locator('.score-value > span').first()).toHaveText('100')
  await page.getByRole('button', { name: '변경한 조합 저장하기' }).click()
  await page.goto('/#saved')
  await page.getByRole('button', { name: '조합 불러오기' }).click()
  await expect(page.locator('.cart-row h2')).toHaveText(['프로틴 A', '레보티록신 경구제'])
  await expect(page.locator('.quantity-control > span').first()).toHaveText('3')
})

test('실제 규칙 SVG와 근거 시트, 로컬 질문 가이드는 API를 호출하지 않는다', async ({ page }) => {
  let calls = 0
  await page.route('**/api/explain', route => { calls++; return route.abort() })
  await page.goto('/#result')
  await expect(page.getByRole('img', { name: /R06.*레보티록신.*칼슘/ })).toBeVisible()
  await expect(page.locator('.relation-heading')).toContainText('−12')
  await page.getByRole('button', { name: '이 관계의 출처와 적용 범위' }).click()
  const dialog = page.getByRole('dialog', { name: '성분 관계 근거' })
  await expect(dialog).toContainText('R06')
  await expect(dialog.locator('.evidence-links a').first()).toHaveAttribute('href', /^https:/)
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await page.getByRole('button', { name: '점수 계산 과정을 알려주세요' }).click()
  await expect(page.locator('.rule-answer')).toContainText('88점')
  await expect(page.locator('.rule-answer')).toContainText('AI 생성 아님')
  await page.getByRole('button', { name: '어떤 정보가 더 필요한가요?' }).click()
  await expect(page.locator('.rule-answer')).toContainText('12개')
  expect(calls).toBe(0)
})

test('탐색 담기 취소·상세 닫기·이전 화면 복귀를 보존한다', async ({ page }) => {
  await page.goto('/#cart')
  await page.getByRole('button', { name: '제품 추가', exact: true }).click()
  await page.getByRole('searchbox').fill('프로틴 B')
  await page.getByRole('button', { name: '프로틴 B 담기 취소', exact: true }).click()
  await expect(page.getByRole('button', { name: /^프로틴 B 조합함에 추가/ })).not.toHaveAccessibleName(/현재/)
  await page.getByRole('button', { name: /^프로틴 B 조합함에 추가/ }).click()
  await page.getByRole('button', { name: '프로틴 B 상세 보기', exact: true }).click()
  await page.getByRole('button', { name: '담기 취소', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: '프로틴 B 상세 보기', exact: true }).click()
  await page.getByRole('button', { name: '닫고 돌아가기', exact: true }).click()
  await page.getByRole('button', { name: '이전 화면으로 돌아가기' }).click()
  await expect(page).toHaveURL(/#cart$/)
  await expect(page.locator('.cart-row h2')).toHaveText(['레보티록신 경구제'])
})

