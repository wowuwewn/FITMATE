const dataURI=async(f,mime)=>`data:${mime};base64,${(await readFile(path.join(root,f))).toString('base64')}`;
const engine=await dataURI('data/analysis.js','text/javascript');
app=app.replace("from './data/analysis.js'",`from '${engine}'`);
